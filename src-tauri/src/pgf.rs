//! 図設定と計算結果から pgfplots のコード（tikzpicture 断片）を生成する。

use crate::figure::{Axis, Computed, Figure, ResolvedAxis, Series};

fn num(v: f64) -> String {
    if v.is_finite() {
        format!("{v:e}")
    } else {
        "nan".into()
    }
}

/// 数式モード外の特殊文字だけをエスケープする（ユーザーは $...$ や \命令 を書いてよい）。
pub fn tex_text(s: &str) -> String {
    let mut out = String::new();
    let mut math = false;
    let mut prev = '\0';
    for c in s.chars() {
        if prev == '\\' {
            out.push(c);
            prev = '\0';
            continue;
        }
        match c {
            '$' => {
                math = !math;
                out.push(c)
            }
            '%' | '&' | '#' => {
                out.push('\\');
                out.push(c)
            }
            '_' | '^' if !math => {
                out.push('\\');
                out.push(c);
                if c == '^' {
                    out.push_str("{}");
                }
            }
            _ => out.push(c),
        }
        prev = c;
    }
    out
}

pub fn unit_tex(unit: &str) -> String {
    if unit.contains('$') {
        tex_text(unit)
    } else if unit.contains(['^', '_', '\\']) {
        format!("$\\mathrm{{{unit}}}$")
    } else {
        tex_text(unit)
    }
}

pub fn axis_label(ax: &Axis) -> String {
    let l = tex_text(ax.label.trim());
    let u = ax.unit.trim();
    if u.is_empty() {
        l
    } else if l.is_empty() {
        format!("[{}]", unit_tex(u))
    } else {
        format!("{l} [{}]", unit_tex(u))
    }
}

fn color_name(i: usize) -> String {
    let mut s = String::from("lrsc");
    let mut k = i;
    loop {
        s.push((b'a' + (k % 26) as u8) as char);
        k /= 26;
        if k == 0 {
            break;
        }
    }
    s
}

fn hex(color: &str) -> String {
    let h: String = color.trim_start_matches('#').chars().filter(|c| c.is_ascii_hexdigit()).collect();
    match h.len() {
        6 => h.to_uppercase(),
        3 => h.chars().flat_map(|c| [c, c]).collect::<String>().to_uppercase(),
        _ => "000000".into(),
    }
}

fn plot_options(s: &Series, color: &str) -> Option<String> {
    let has_line = s.line_style != "none";
    let has_mark = s.marker != "none" && !s.marker.is_empty();
    if !has_line && !has_mark {
        return None;
    }
    let mut o = vec![format!("color={color}")];
    if has_line {
        o.push(format!("line width={}pt", s.line_width.max(0.05)));
        match s.line_style.as_str() {
            "dashed" => o.push("dashed".into()),
            "dotted" => o.push("dotted".into()),
            "dashdotted" => o.push("dashdotted".into()),
            _ => o.push("solid".into()),
        }
    } else {
        o.push("only marks".into());
    }
    if has_mark {
        o.push(format!("mark={}", s.marker));
        o.push(format!("mark size={}pt", s.marker_size.max(0.1)));
        o.push("mark options={solid, line width=0.6pt}".into());
    } else {
        o.push("mark=none".into());
    }
    Some(o.join(", "))
}

fn axis_options(o: &mut Vec<String>, k: char, ax: &Axis, r: &ResolvedAxis) {
    if r.log {
        o.push(format!("{k}mode=log"));
    }
    o.push(format!("{k}min={}, {k}max={}", num(r.min), num(r.max)));
    if !r.log {
        let ticks: Vec<String> = r.ticks.iter().map(|t| num(t.v)).collect();
        let labels: Vec<String> = r.ticks.iter().map(|t| format!("{{${}$}}", t.label)).collect();
        o.push(format!("{k}tick={{{}}}", ticks.join(",")));
        o.push(format!("{k}ticklabels={{{}}}", labels.join(",")));
        o.push(format!("scaled {k} ticks=false"));
    }
    let label = axis_label(ax);
    if !label.is_empty() {
        o.push(format!("{k}label={{{label}}}"));
    }
    if ax.grid {
        o.push(format!("{k}majorgrids"));
    }
}

fn coords(points: &[[f64; 2]]) -> String {
    let mut s = String::new();
    for (i, p) in points.iter().enumerate() {
        if i > 0 && i % 4 == 0 {
            s.push('\n');
        }
        s.push_str(&format!("({},{}) ", num(p[0]), num(p[1])));
    }
    s
}

pub fn generate(fig: &Figure, c: &Computed) -> String {
    let mut t = String::new();
    t.push_str("% Generated by LabReport Studio. Do not edit: regenerated from the figure settings (JSON).\n");
    t.push_str("% To \\input this file, load pgfplots in the preamble: \\usepackage{pgfplots}\\pgfplotsset{compat=1.18}\n");
    t.push_str("\\begin{tikzpicture}\n");
    for (i, s) in fig.series.iter().enumerate() {
        t.push_str(&format!("\\definecolor{{{}}}{{HTML}}{{{}}}\n", color_name(i), hex(&s.color)));
    }
    let fs = fig.font_size.clamp(4.0, 40.0);
    let mut o = vec![
        "name=lrsaxis".to_string(),
        format!("width={}cm, height={}cm, scale only axis", fig.width.max(1.0), fig.height.max(1.0)),
        format!("font=\\fontsize{{{}pt}}{{{}pt}}\\selectfont", fs, fs * 1.2),
        "unbounded coords=jump".into(),
        "legend cell align=left".into(),
    ];
    axis_options(&mut o, 'x', &fig.x_axis, &c.x_axis);
    axis_options(&mut o, 'y', &fig.y_axis, &c.y_axis);
    let legend_on = fig.legend_pos != "none";
    if legend_on {
        o.push(format!("legend pos={}", fig.legend_pos));
    }
    t.push_str(&format!("\\begin{{axis}}[\n  {}\n]\n", o.join(",\n  ")));

    let mut notes = String::new();
    for (i, (s, cs)) in fig.series.iter().zip(&c.series).enumerate() {
        if !s.visible || cs.points.is_empty() {
            continue;
        }
        let col = color_name(i);
        let Some(mut opts) = plot_options(s, &col) else { continue };
        let entry = legend_on && !s.legend.trim().is_empty();
        if !entry {
            opts.push_str(", forget plot");
        }
        t.push_str(&format!("\\addplot[{opts}] coordinates {{\n{}\n}};\n", coords(&cs.points)));
        if entry {
            t.push_str(&format!("\\addlegendentry{{{}}}\n", tex_text(s.legend.trim())));
        }
        if let (Some(th), true) = (&cs.theory, s.highlight) {
            if !th.outliers.is_empty() {
                t.push_str(&format!(
                    "\\addplot[only marks, mark=o, mark size={}pt, color=red, line width=1pt, forget plot] coordinates {{\n{}\n}};\n",
                    (s.marker_size.max(2.0) + 2.5),
                    coords(&th.outliers)
                ));
            }
        }
        if let Some(f) = &cs.fit {
            let mut lines = Vec::new();
            if s.show_equation {
                lines.push(format!("${}$", f.equation_latex));
            }
            if s.show_r2 && f.r2.is_finite() {
                lines.push(format!("$R^2 = {:.4}$", f.r2));
            }
            if !lines.is_empty() {
                notes.push_str(&format!(
                    "\\node[anchor=north west, align=left, inner sep=2pt, text={col}] at (rel axis cs:{},{}) {{{}}};\n",
                    s.eq_pos[0],
                    s.eq_pos[1],
                    lines.join("\\\\ ")
                ));
            }
        }
    }
    t.push_str(&notes);
    t.push_str("\\end{axis}\n");
    let fnt = format!("font=\\fontsize{{{}pt}}{{{}pt}}\\selectfont", fs, fs * 1.2);
    if c.x_axis.exp != 0 {
        t.push_str(&format!(
            "\\node[anchor=north east, inner sep=1pt, yshift=-{}pt, {fnt}] at (lrsaxis.south east) {{$\\times 10^{{{}}}$}};\n",
            fs * 1.7,
            c.x_axis.exp
        ));
    }
    if c.y_axis.exp != 0 {
        t.push_str(&format!(
            "\\node[anchor=south west, inner sep=1pt, yshift=2pt, {fnt}] at (lrsaxis.north west) {{$\\times 10^{{{}}}$}};\n",
            c.y_axis.exp
        ));
    }
    t.push_str("\\end{tikzpicture}\n");
    t
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escaping() {
        assert_eq!(tex_text("50% of $V_0$ & R_1"), "50\\% of $V_0$ \\& R\\_1");
        assert_eq!(tex_text("already \\% ok"), "already \\% ok");
        assert_eq!(unit_tex("m/s^2"), "$\\mathrm{m/s^2}$");
        assert_eq!(unit_tex("V"), "V");
    }
}
